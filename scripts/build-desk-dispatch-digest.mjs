function report(lines, outputs = {}, { sink = true } = {}) {
  for (const l of lines) console.log(l);
  if (!sink) return;
  if (process.env.GITHUB_STEP_SUMMARY) fs.appendFileSync(process.env.GITHUB_STEP_SUMMARY, `${lines.join('\n')}\n`);
  if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, Object.entries(outputs).map(([k, v]) => `${k}=${v}\n`).join(''));
}

/**
 * Production liveness. A Desk edition is committed to main by its publisher and
 * reaches production through a separate content release, so a story can exist
 * in the corpus while its page is still a 404 (observed 2026-10-02). An email
 * linking to a page that does not exist is worse than a shorter email, so a
 * definite 404/410 drops the story (or its art); anything else that is not a
 * clean 2xx — a bot challenge, a 5xx, a timeout — is "unverified" and kept,
 * because the page usually exists and blocking every send on edge weather would
 * silently stop the Dispatch.
 */
export async function liveStatus(url, fetchImpl = fetch) {
  try {
    const res = await fetchImpl(url, { method: 'HEAD', redirect: 'follow', signal: AbortSignal.timeout(15_000) });
    if (res.status >= 200 && res.status < 300) return 'live';
    if (res.status === 404 || res.status === 410) return 'missing';
    return 'unverified';
  } catch { return 'unverified'; }
}

export const canonicalPath = (date, slug) => `${SITE}/news/${date}/${slug}/`;

export async function probeDay(day, date, fetchImpl) {
  const stories = (day?.stories || []).filter((s) => s && s.slug);
  return Promise.all(stories.map(async (s) => ({
    slug: s.slug,
    page: await liveStatus(canonicalPath(date, s.slug), fetchImpl),
    art: await liveStatus(`${SITE}/assets/og/news/${date}--${s.slug}.png`, fetchImpl),
  })));
}

