/* ── Brevo ──────────────────────────────────────────────────────────────── */

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/** One Brevo call with bounded retry on transient (network / 429 / 5xx) failures only. */
export async function brevo(pathname, { method = 'GET', body, key, fetchImpl = fetch, attempts = 3, backoffMs = 1500 } = {}) {
  let last = null;
  for (let i = 0; i < attempts; i += 1) {
    try {
      const res = await fetchImpl(`${BREVO_API}${pathname}`, {
        method,
        headers: { 'api-key': key, accept: 'application/json', ...(body ? { 'content-type': 'application/json' } : {}) },
        body: body ? JSON.stringify(body) : undefined,
        signal: AbortSignal.timeout(20_000),
      });
      const text = await res.text();
      let json = null;
      try { json = text ? JSON.parse(text) : null; } catch { /* non-JSON body */ }
      if (res.status === 429 || res.status >= 500) { last = { status: res.status, text }; await sleep(backoffMs * (i + 1)); continue; }
      return { ok: res.ok, status: res.status, json, text };
    } catch (err) {
      last = { status: 0, text: String(err?.message || err) };
      if (i < attempts - 1) await sleep(backoffMs * (i + 1));
    }
  }
  return { ok: false, status: last?.status ?? 0, json: null, text: last?.text || 'unreachable', transient: true };
}

/** Find this day's campaign by its exact name (newest first, bounded scan). */
export async function findCampaign(name, opts) {
  for (let offset = 0; offset < 500; offset += 100) {
    const res = await brevo(`/emailCampaigns?type=classic&limit=100&offset=${offset}&sort=desc&excludeHtmlContent=true`, opts);
    if (!res.ok) throw new Error(`Brevo campaign list unreadable (HTTP ${res.status}) — refusing to send blind`);
    const rows = Array.isArray(res.json?.campaigns) ? res.json.campaigns : [];
    const hit = rows.find((c) => c && c.name === name);
    if (hit) return hit;
    if (rows.length < 100) return null;
  }
  return null;
}

