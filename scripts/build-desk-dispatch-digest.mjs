export function parseArgs(argv) {
  const opts = { mode: 'dry-run', date: null, dayFile: null, testTo: null };
  const modes = [];
  for (let i = 0; i < argv.length; i += 1) {
    const a = argv[i];
    const val = () => { const v = argv[i + 1]; if (!v || v.startsWith('--')) throw new Error(`${a} needs a value`); i += 1; return v; };
    if (a === '--dry-run') modes.push('dry-run');
    else if (a === '--send') modes.push('send');
    else if (a === '--self-test') modes.push('self-test');
    else if (a === '--test-to') { modes.push('test'); opts.testTo = val().trim().toLowerCase(); }
    else if (a === '--date') opts.date = val();
    else if (a === '--day-file') opts.dayFile = val();
    else throw new Error(`Unknown argument ${a}`);
  }
  if (modes.length > 1) throw new Error('Pick one mode: --dry-run | --test-to <email> | --send | --self-test');
  if (modes.length) opts.mode = modes[0];
  if (opts.date !== null && !DATE_RE.test(opts.date)) throw new Error('--date must be YYYY-MM-DD');
  if (opts.mode === 'test' && (!EMAIL_RE.test(opts.testTo) || opts.testTo.length > 254)) throw new Error('--test-to needs one valid email address');
  return opts;
}

