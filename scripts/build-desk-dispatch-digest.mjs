/**
 * Campaign send. Idempotent by name: an already-dispatched campaign for this day
 * is reported and left alone; a leftover draft is refreshed and sent; otherwise a
 * new campaign is created and sent. Returns { outcome, id?, status? }.
 */
export async function sendCampaign(issue, html, opts) {
  const existing = await findCampaign(issue.name, opts);
  let id;
  if (existing) {
    if (DISPATCHED.has(existing.status)) return { outcome: 'already-sent', id: existing.id, status: existing.status };
    if (existing.status !== 'draft') throw new Error(`Campaign ${issue.name} exists with status "${existing.status}" — needs a human look, refusing to send`);
    id = existing.id;
    const upd = await brevo(`/emailCampaigns/${id}`, { ...opts, method: 'PUT', body: campaignPayload(issue, html) });
    if (!upd.ok) throw new Error(`Brevo campaign update failed (HTTP ${upd.status}): ${upd.text.slice(0, 200)}`);
  } else {
    const created = await brevo('/emailCampaigns', { ...opts, method: 'POST', body: campaignPayload(issue, html) });
    if (!created.ok || !created.json?.id) throw new Error(`Brevo campaign create failed (HTTP ${created.status}): ${created.text.slice(0, 200)}`);
    id = created.json.id;
  }
  // Not retried: a transient failure here must never become a second send.
  const sent = await brevo(`/emailCampaigns/${id}/sendNow`, { ...opts, method: 'POST', attempts: 1 });
  if (!sent.ok) throw new Error(`Brevo sendNow failed for campaign ${id} (HTTP ${sent.status}): ${sent.text.slice(0, 200)}`);
  const check = await brevo(`/emailCampaigns/${id}?excludeHtmlContent=true`, opts);
  return { outcome: 'sent', id, status: check.json?.status || 'unknown' };
}

