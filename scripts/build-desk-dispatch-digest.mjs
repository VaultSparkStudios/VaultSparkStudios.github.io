/** The lead voice: the persona who opens the written piece, as the article byline does. */
export function leadPersona(story) {
  const id = (story.body || []).find((b) => b && b.voice)?.voice
    || story.memeLine?.personaId
    || story.stances?.[0]?.personaId;
  return personaById(id);
}

/**
 * Pick the day's stories: the declared lead first, then the hottest arguments,
 * ties broken by edition order. Capped at MAX_STORIES; a thin day ships what it
 * has rather than padding — nothing is ever invented to reach MIN_STORIES.
 */
export function selectStories(day) {
  const order = new Map(EDITIONS.map((e, i) => [e.id, i]));
  const stories = (day?.stories || []).filter((s) => s && s.slug && s.headline);
  const ranked = stories
    .map((s, i) => ({ s, i, heat: heatBreakdown(s.stances || []).heat }))
    .sort((a, b) => (Number(b.s.slug === day.leadSlug) - Number(a.s.slug === day.leadSlug))
      || (b.heat - a.heat)
      || ((order.get(a.s.edition) ?? 9) - (order.get(b.s.edition) ?? 9))
      || (a.i - b.i));
  return ranked.slice(0, MAX_STORIES).map((r) => r.s);
}

/**
 * "From the panel": one line, only when the panel genuinely split on a verdict.
 * Chooses the hottest selected story whose stances carry at least two different
 * verdicts and quotes the two most opposed voices. Uniform agreement yields null
 * — a manufactured disagreement would misreport the desk.
 */
export function panelHighlight(stories, date) {
  let best = null;
  for (const story of stories) {
    const stances = (story.stances || []).filter((s) => personaById(s.personaId) && s.verdict);
    if (new Set(stances.map((s) => s.verdict)).size < 2) continue;
    const { heat, shape } = heatBreakdown(stances);
    if (!best || heat > best.heat) best = { story, stances, heat, shape };
  }
  if (!best) return null;
  const sorted = [...best.stances].sort((a, b) => (b.direction - a.direction) || (b.confidence - a.confidence));
  let hi = sorted[0];
  let lo = [...sorted].reverse().find((s) => s.verdict !== hi.verdict);
  if (!lo) return null;
  const a = personaById(hi.personaId);
  const b = personaById(lo.personaId);
  return {
    slug: best.story.slug,
    headline: best.story.headline,
    url: storyUrl(date, best.story.slug),
    heat: best.heat,
    a: { name: a.name, verdict: hi.verdict },
    b: { name: b.name, verdict: lo.verdict },
    text: `${a.name} calls it ${hi.verdict}; ${b.name} calls it ${lo.verdict}.`,
  };
}

/**
 * Build the issue model. Returns { skip: true, reason } when there is nothing to
 * send: a missing day, a simulated (dry-run pipeline) day, or a day with no
 * stories. Pure — no I/O.
 */
export function buildDigest(day, { date, noArt = new Set() } = {}) {
  if (!day) return { skip: true, reason: `no Desk day artifact for ${date}` };
  if (date && day.date && day.date !== date) return { skip: true, reason: `day artifact is dated ${day.date}, not ${date}` };
  if (day.simulated) return { skip: true, reason: `${day.date} is a simulated (preview) day — not real editions` };
  const issueDate = day.date || date;
  const picked = selectStories(day);
  if (!picked.length) return { skip: true, reason: `no new Desk editions on ${issueDate}` };
  const editions = EDITIONS.filter((e) => (day.stories || []).some((s) => s.edition === e.id)).map((e) => e.name);
  const stories = picked.map((s) => {
    const persona = leadPersona(s);
    return {
      slug: s.slug,
      headline: s.headline,
      dek: s.hook || '',
      edition: editionById(s.edition)?.name || null,
      url: storyUrl(issueDate, s.slug),
      persona: persona ? { id: persona.id, name: persona.name, tagline: persona.tagline } : null,
      image: noArt.has(s.slug) ? null : `${SITE}/assets/og/news/${issueDate}--${s.slug}.png`,
      imageAlt: s.visual?.alt || '',
    };
  });
  const lead = stories[0];
  const subject = clamp(`The Desk Dispatch, ${shortDate(issueDate)}: ${lead.headline}`, 110);
  return {
    skip: false,
    date: issueDate,
    name: campaignName(issueDate),
    subject,
    preheader: clamp(lead.dek || `${stories.length} stories from today's Desk.`, 140),
    editions,
    totalStories: (day.stories || []).length,
    stories,
    panel: panelHighlight(picked, issueDate),
    deskUrl: deskUrl(issueDate, 'masthead'),
  };
}

function clamp(text, max) {
  const t = String(text).replace(/\s+/g, ' ').trim();
  return t.length <= max ? t : `${t.slice(0, max - 1).replace(/\s+\S*$/, '')}…`;
}

