#!/usr/bin/env node
/**
 * build-geo-vitals.mjs (S175 #8 · multi-geo vitals)
 *
 * The original audit recipe ("synthetic traces from US/EU/Asia GH runners")
 * is not feasible free — GitHub hosted runners don't offer geo selection.
 * Better: every RUM beacon already records cf.colo + cf.country, so REAL
 * multi-geo performance data accrues from real visitors. This rolls raw RUM
 * into per-country vitals so "slow only in Europe" problems surface without
 * paid tooling.
 *
 * Privacy: aggregates only; countries below MIN_SAMPLES are bucketed into
 * "other" so no single visit is identifiable.
 *
 * Output: api/geo-vitals.json
 * Usage:  node scripts/build-geo-vitals.mjs [--check|--self-test]
 */
import childProcess from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const RAW_DIR = path.join(ROOT, '.cache', 'rum-raw');
const COLO_SUPPLEMENT = path.join(ROOT, '.cache', 'probe-colo-supplement.ndjson');
const OUT = path.join(ROOT, 'api', 'geo-vitals.json');
const CHECK = process.argv.includes('--check');
const MIN_SAMPLES = 3;

/**
 * S300: statistical confidence, kept SEPARATE from the privacy floor.
 *
 * MIN_SAMPLES is a k-anonymity contract — below it a country is bucketed as
 * "other" so individuals are not identifiable. It says nothing about whether the
 * resulting p75 means anything, and the two must not be conflated: raising
 * MIN_SAMPLES to a statistically respectable number would bucket GB, IN, CA and
 * CN into "other" and DESTROY the signal rather than qualify it.
 *
 * The prompting case: CA reported lcpP75 9960ms against US 992ms — a 10x gap on
 * SIX samples. A p75 over six samples is one bad session away from fiction, and
 * rendering it beside a 464-sample US figure in the same visual weight invites
 * exactly the wrong action (chasing a phantom regression, or worse, lowering a
 * budget to accommodate it).
 *
 * So the number is retained and LABELLED. Consumers render `low` rows as
 * "insufficient samples", never as a measurement.
 */
export const CONFIDENCE_SAMPLES = 20;

export function confidenceFor(samples) {
  return Number.isInteger(samples) && samples >= CONFIDENCE_SAMPLES ? 'high' : 'low';
}

// Load synthetic colo-probe rows (generated by probe-uptime.mjs --colo-probe).
// These are transparent: labeled synthetic:true and only supplement thin regions.
function loadColoSupplement() {
  if (!fs.existsSync(COLO_SUPPLEMENT)) return [];
  try {
    return fs.readFileSync(COLO_SUPPLEMENT, 'utf8').split('\n').filter(Boolean).map((l) => {
      const p = JSON.parse(l);
      // Convert probe row → RUM-like row so rollupGeo can consume it.
      return { route: '/', vitals: { lcp: p.ttfb * 3, ttfb: p.ttfb }, cf: { country: p.country, colo: p.colo }, synthetic: true };
    });
  } catch { return []; }
}

export function rollupGeo(rows) {
  const byCountry = new Map();
  for (const r of rows) {
    if (!r || !r.cf?.country || r.route?.startsWith('/__')) continue;
    const lcp = r.vitals?.lcp;
    if (!Number.isFinite(lcp)) continue;
    if (!byCountry.has(r.cf.country)) byCountry.set(r.cf.country, { lcps: [], ttfbs: [], colos: new Set() });
    const c = byCountry.get(r.cf.country);
    c.lcps.push(lcp);
    if (Number.isFinite(r.vitals?.ttfb)) c.ttfbs.push(r.vitals.ttfb);
    if (r.cf.colo) c.colos.add(r.cf.colo);
  }
  const p75 = (a) => { if (!a.length) return null; const s = [...a].sort((x, y) => x - y); return s[Math.min(s.length - 1, Math.floor(s.length * 0.75))]; };
  const countries = [];
  const other = { lcps: [], ttfbs: [], colos: new Set() };
  for (const [country, c] of byCountry) {
    if (c.lcps.length >= MIN_SAMPLES) {
      countries.push({ country, samples: c.lcps.length, lcpP75: p75(c.lcps), ttfbP75: p75(c.ttfbs), confidence: confidenceFor(c.lcps.length), colos: [...c.colos].sort() });
    } else {
      other.lcps.push(...c.lcps);
      other.ttfbs.push(...c.ttfbs);
      for (const colo of c.colos) other.colos.add(colo);
    }
  }
  countries.sort((a, b) => b.samples - a.samples || a.country.localeCompare(b.country));
  if (other.lcps.length) {
    countries.push({ country: 'other', samples: other.lcps.length, lcpP75: p75(other.lcps), ttfbP75: p75(other.ttfbs), confidence: confidenceFor(other.lcps.length), colos: [...other.colos].sort() });
  }
  return countries;
}

/**
 * Validate the shape + privacy contract of a geo-vitals payload.
 *
 * Worth more than the byte-compare it replaces when the supplement is absent:
 * byte-equality only ever proved "these bytes match some other bytes". This
 * asserts the promise the file makes to the public — no country below
 * MIN_SAMPLES is ever named (sub-threshold rows must be bucketed as "other"),
 * so no single visit is identifiable.
 */
export function validateGeoVitalsShape(doc) {
  const problems = [];
  if (!doc || typeof doc !== 'object') return { ok: false, problems: ['payload is not an object'] };
  if (doc.schemaVersion !== '1.0') problems.push(`schemaVersion ${JSON.stringify(doc.schemaVersion)} !== "1.0"`);
  if (doc.publicSafe !== true) problems.push('publicSafe must be true (this feed is public)');
  if (doc.generatedBy !== 'scripts/build-geo-vitals.mjs') problems.push(`generatedBy ${JSON.stringify(doc.generatedBy)} unexpected`);
  if (doc.minSamples !== MIN_SAMPLES) problems.push(`minSamples ${doc.minSamples} !== ${MIN_SAMPLES}`);
  if (!Number.isFinite(Date.parse(doc.generatedAt))) problems.push('generatedAt is not a valid ISO timestamp');
  if (!Array.isArray(doc.countries)) {
    problems.push('countries must be an array');
    return { ok: problems.length === 0, problems };
  }
  for (const c of doc.countries) {
    const label = c?.country ?? '<missing>';
    if (typeof c?.country !== 'string' || !c.country) problems.push('a country entry has no country code');
    if (!Number.isInteger(c?.samples) || c.samples < 1) problems.push(`${label}: samples must be a positive integer`);
    if (!Array.isArray(c?.colos)) problems.push(`${label}: colos must be an array`);
    if (c?.lcpP75 !== null && !Number.isFinite(c?.lcpP75)) problems.push(`${label}: lcpP75 must be a number or null`);
    // The privacy contract: only the "other" bucket may sit below MIN_SAMPLES.
    if (c?.country !== 'other' && Number.isInteger(c?.samples) && c.samples < MIN_SAMPLES) {
      problems.push(`${label}: ${c.samples} samples is below minSamples=${MIN_SAMPLES} and must be bucketed as "other" (privacy)`);
    }
    // S300: every row must be labelled, and the label must match the count.
    // An unlabelled row renders as a fact; a MIS-labelled one is worse, because
    // it launders a six-sample p75 as high confidence.
    if (c?.confidence !== 'high' && c?.confidence !== 'low') {
      problems.push(`${label}: confidence must be "high" or "low" (got ${JSON.stringify(c?.confidence)})`);
    } else if (Number.isInteger(c?.samples) && c.confidence !== confidenceFor(c.samples)) {
      problems.push(`${label}: confidence "${c.confidence}" contradicts ${c.samples} samples (threshold ${CONFIDENCE_SAMPLES})`);
    }
  }
  if (doc.confidenceSamples !== CONFIDENCE_SAMPLES) {
    problems.push(`confidenceSamples ${doc.confidenceSamples} !== ${CONFIDENCE_SAMPLES} (the threshold must be published, not implicit)`);
  }
  return { ok: problems.length === 0, problems };
}

if (process.argv.includes('--self-test')) {
  const rows = [
    ...Array.from({ length: 4 }, (_, i) => ({ route: '/', vitals: { lcp: 1000 + i, ttfb: 100 }, cf: { country: 'US', colo: 'DFW' } })),
    { route: '/', vitals: { lcp: 9000, ttfb: 900 }, cf: { country: 'DE', colo: 'FRA' } },
    { route: '/__rum_selftest', vitals: { lcp: 1 }, cf: { country: 'US', colo: 'DFW' } },
  ];
  const g = rollupGeo(rows);
  const validDoc = {
    schemaVersion: '1.0',
    generatedAt: new Date().toISOString(),
    generatedBy: 'scripts/build-geo-vitals.mjs',
    publicSafe: true,
    note: 'x',
    minSamples: MIN_SAMPLES,
    confidenceSamples: CONFIDENCE_SAMPLES,
    countries: g,
  };
  // A real rollup must always satisfy its own validator.
  const validRes = validateGeoVitalsShape(validDoc);
  // Privacy violation: a named country below MIN_SAMPLES must be rejected.
  const leaky = { ...validDoc, countries: [{ country: 'DE', samples: 1, lcpP75: 9000, ttfbP75: 900, confidence: 'low', colos: ['FRA'] }] };
  const leakyRes = validateGeoVitalsShape(leaky);
  // "other" is the one bucket allowed below the threshold.
  const otherOk = validateGeoVitalsShape({ ...validDoc, countries: [{ country: 'other', samples: 1, lcpP75: 10, ttfbP75: 5, confidence: 'low', colos: ['FRA'] }] });
  const badSchema = validateGeoVitalsShape({ ...validDoc, schemaVersion: '0.9' });
  const notPublic = validateGeoVitalsShape({ ...validDoc, publicSafe: false });

  const checks = [
    ['US quoted (>=3 samples)', g.some((c) => c.country === 'US' && c.samples === 4)],
    ['DE bucketed into other', !g.some((c) => c.country === 'DE') && g.some((c) => c.country === 'other')],
    ['selftest route excluded', g.find((c) => c.country === 'US').samples === 4],
    ['p75 computed', Number.isFinite(g[0].lcpP75)],
    ['validator accepts a real rollup', validRes.ok],
    ['validator rejects sub-threshold named country (privacy)', !leakyRes.ok && leakyRes.problems.some((p) => /privacy/.test(p))],
    ['validator allows "other" below threshold', otherOk.ok],
    ['validator rejects wrong schemaVersion', !badSchema.ok],
    ['validator rejects publicSafe:false', !notPublic.ok],

    // S300 confidence labelling — kept distinct from the privacy floor.
    ['a thin country is labelled low confidence', g.find((c) => c.country === 'US').confidence === 'low'],
    ['the "other" bucket is labelled too', g.find((c) => c.country === 'other').confidence === 'low'],
    ['THE LIVE CASE: 6 samples is low confidence', confidenceFor(6) === 'low'],
    ['a well-sampled country is high confidence', confidenceFor(464) === 'high'],
    ['exactly at the threshold is high', confidenceFor(CONFIDENCE_SAMPLES) === 'high'],
    ['just under the threshold is low', confidenceFor(CONFIDENCE_SAMPLES - 1) === 'low'],
    ['confidence is INDEPENDENT of the privacy floor', MIN_SAMPLES !== CONFIDENCE_SAMPLES && confidenceFor(MIN_SAMPLES) === 'low'],
    ['an unlabelled row is REJECTED', !validateGeoVitalsShape({ ...validDoc, countries: [{ country: 'US', samples: 30, lcpP75: 1, ttfbP75: 1, colos: [] }] }).ok],
    ['a MIS-labelled row is REJECTED', !validateGeoVitalsShape({ ...validDoc, countries: [{ country: 'US', samples: 6, lcpP75: 1, ttfbP75: 1, confidence: 'high', colos: [] }] }).ok],
    ['the mislabel names the contradiction', validateGeoVitalsShape({ ...validDoc, countries: [{ country: 'US', samples: 6, lcpP75: 1, ttfbP75: 1, confidence: 'high', colos: [] }] }).problems.some((x) => /contradicts/.test(x))],
    ['an unpublished threshold is REJECTED', !validateGeoVitalsShape({ ...validDoc, confidenceSamples: undefined }).ok],
  ];
  let pass = 0;
  for (const [name, ok] of checks) { console.log(`  ${ok ? '✓' : '✗'} ${name}`); if (ok) pass++; }
  console.log(`build-geo-vitals --self-test: ${pass}/${checks.length}`);
  process.exit(pass === checks.length ? 0 : 1);
}

function listRawRumFiles() {
  try {
    const out = childProcess.execFileSync('git', ['ls-files', '--', '.cache/rum-raw'], {
      cwd: ROOT,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    const tracked = out.split('\n').filter((line) => line.endsWith('.json')).sort();
    if (tracked.length) return tracked.map((file) => path.join(ROOT, file));
  } catch { /* fall back to filesystem traversal */ }

  const files = [];
  if (!fs.existsSync(RAW_DIR)) return files;
  for (const day of fs.readdirSync(RAW_DIR).sort()) {
    const dir = path.join(RAW_DIR, day);
    if (!fs.statSync(dir).isDirectory()) continue;
    for (const f of fs.readdirSync(dir).sort()) {
      if (f.endsWith('.json')) files.push(path.join(dir, f));
    }
  }
  return files;
}

const rows = [];
const rawDays = new Set();
for (const file of listRawRumFiles()) {
  try {
    const j = JSON.parse(fs.readFileSync(file, 'utf8'));
    rows.push(...(Array.isArray(j) ? j : [j]));
    const day = /dt=(\d{4}-\d{2}-\d{2})/.exec(file)?.[1];
    if (day) rawDays.add(day);
  } catch { /* skip */ }
}
// The observation window is derived from the INPUT corpus, never wall-clock:
// a fresh generatedAt over a month-old corpus must not read as fresh evidence.
const sortedDays = [...rawDays].sort();
const dataWindow = sortedDays.length
  ? { firstDay: sortedDays[0], lastDay: sortedDays.at(-1), days: sortedDays.length }
  : null;
// Supplement with colo-probe synthetic rows (only for countries with < MIN_SAMPLES real data).
const realByCountry = new Set(rows.filter((r) => r?.cf?.country).map((r) => r.cf.country));
const supplement = loadColoSupplement().filter((r) => {
  const c = r?.cf?.country;
  return c && !realByCountry.has(c);
});
rows.push(...supplement);
const payload = {
  schemaVersion: '1.0',
  generatedAt: new Date().toISOString(),
  generatedBy: 'scripts/build-geo-vitals.mjs',
  publicSafe: true,
  note: `Per-country field vitals from real visits. Countries under ${MIN_SAMPLES} samples are bucketed as "other" (privacy). Rows under ${CONFIDENCE_SAMPLES} samples are confidence:"low" — render those as "insufficient samples", not as a measurement. dataWindow reports when the underlying visits actually happened; readers must surface staleness rather than trusting generatedAt.`,
  minSamples: MIN_SAMPLES,
  confidenceSamples: CONFIDENCE_SAMPLES,
  dataWindow,
  countries: rollupGeo(rows),
};

if (CHECK) {
  if (!fs.existsSync(OUT)) { console.error('build-geo-vitals --check: missing output'); process.exit(1); }
  const cur = JSON.parse(fs.readFileSync(OUT, 'utf8'));

  // Structural + privacy invariants — always enforced, reproducible anywhere.
  const structural = validateGeoVitalsShape(cur);
  if (!structural.ok) {
    console.error('build-geo-vitals --check: invalid output —');
    for (const p of structural.problems) console.error(`  ✗ ${p}`);
    process.exit(1);
  }

  // Byte-equality is only a VALID test when every input is reproducible here.
  // The colo supplement is Actions-cache-only by design (uptime-probe.yml
  // caches it rather than committing api/geo-vitals.json every 30 min), so a
  // machine without that cache CANNOT reproduce supplement-derived rows.
  // Byte-comparing anyway reports "drift" when nothing drifted — a lying gate
  // (CANON-031). It fired for real: the S281 cron commit landed
  // supplement-derived rows under [skip ci], arming a guaranteed e2e.yml
  // build:check failure on the next ordinary push. Enforce what is knowable.
  if (!fs.existsSync(COLO_SUPPLEMENT)) {
    console.log(`build-geo-vitals --check: structure ok (${cur.countries.length} bucket(s)) · byte-compare skipped — colo supplement absent (Actions-cache-only input; supplement-derived rows are not reproducible here)`);
    process.exit(0);
  }

  if (JSON.stringify({ ...cur, generatedAt: '' }) !== JSON.stringify({ ...payload, generatedAt: '' })) {
    console.error('build-geo-vitals --check: drift; run node scripts/build-geo-vitals.mjs');
    process.exit(1);
  }
  console.log(`build-geo-vitals --check: ok (${payload.countries.length} bucket(s), supplement present)`);
  process.exit(0);
}
fs.writeFileSync(OUT, JSON.stringify(payload, null, 2) + '\n');
console.log(`build-geo-vitals → api/geo-vitals.json (${payload.countries.map((c) => `${c.country}:${c.samples}`).join(' · ') || 'no rows yet'})`);
