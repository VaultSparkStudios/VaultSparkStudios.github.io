#!/usr/bin/env node
/* inject-collection-jsonld.mjs — S196 collection structured-data rung.

   The gap this closes: every journal ENTRY already carries Article/BlogPosting schema
   (shipped pre-S196), but the LISTING pages carry only a BreadcrumbList. journal/index
   declares a bare `Blog` node that never lists its posts, and journal/archive,
   journal/dispatches and changelog declare no collection schema at all. So a crawler or
   answer-engine sees a pile of links instead of "this is a publication with N dated
   posts." This is the structured-data rung directly above the S195 breadcrumb wave.

   It derives the post list from the entries' OWN BlogPosting schema (single source of
   truth — add a post and it auto-registers), and injects a marker-delimited ItemList /
   CollectionPage block before </head> on each listing page. Idempotent: the marked block
   is fully replaced each run, so re-running is a no-op.

   Import-safe: side effects run only when invoked directly.
   Usage:
     node scripts/inject-collection-jsonld.mjs            # inject/refresh blocks
     node scripts/inject-collection-jsonld.mjs --check    # verify coverage (build gate)
     node scripts/inject-collection-jsonld.mjs --self-test
*/
import { readFileSync, writeFileSync, existsSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROD = 'https://vaultsparkstudios.com';
const START = '<!-- collection-jsonld:start (generated by inject-collection-jsonld.mjs) -->';
const END = '<!-- collection-jsonld:end -->';

// Read every real journal entry's BlogPosting and return {url, headline, datePublished}.
export function discoverEntries(root = ROOT) {
  const dir = join(root, 'journal');
  const skip = new Set(['_drafts', 'archive', 'dispatches']);
  const out = [];
  for (const name of readdirSync(dir)) {
    if (skip.has(name)) continue;
    const f = join(dir, name, 'index.html');
    if (!existsSync(f)) continue;
    const html = readFileSync(f, 'utf8');
    const headline = (html.match(/"headline":\s*"([^"]+)"/) || [])[1];
    const url = (html.match(/"url":\s*"(https:\/\/vaultsparkstudios\.com\/journal\/[^"]+)"/) || [])[1]
      || `${PROD}/journal/${name}/`;
    const datePublished = (html.match(/"datePublished":\s*"([^"]+)"/) || [])[1] || null;
    if (headline) out.push({ slug: name, url, headline, datePublished });
  }
  // Newest first (stable: tiebreak on slug so output is deterministic).
  out.sort((a, b) => (b.datePublished || '').localeCompare(a.datePublished || '') || a.slug.localeCompare(b.slug));
  return out;
}

// Build the JSON-LD payload for a given page kind.
export function buildLd(kind, entries) {
  const itemList = {
    '@type': 'ItemList',
    itemListElement: entries.map((e, i) => ({
      '@type': 'ListItem',
      position: i + 1,
      url: e.url,
      name: e.headline,
    })),
  };
  if (kind === 'journal') {
    return {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      name: 'Signal Log — VaultSpark Studios',
      url: `${PROD}/journal/`,
      isPartOf: { '@type': 'WebSite', url: PROD },
      mainEntity: itemList,
    };
  }
  if (kind === 'archive') {
    return {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      name: 'Signal Log Archive — VaultSpark Studios',
      url: `${PROD}/journal/archive/`,
      isPartOf: { '@type': 'CollectionPage', url: `${PROD}/journal/` },
      mainEntity: itemList,
    };
  }
  if (kind === 'dispatches') {
    return {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      name: 'Insider Dispatches — VaultSpark Studios',
      url: `${PROD}/journal/dispatches/`,
      isPartOf: { '@type': 'CollectionPage', url: `${PROD}/journal/` },
    };
  }
  if (kind === 'changelog') {
    return {
      '@context': 'https://schema.org',
      '@type': 'CollectionPage',
      name: 'Changelog — VaultSpark Studios',
      url: `${PROD}/changelog/`,
      isPartOf: { '@type': 'WebSite', url: PROD },
    };
  }
  throw new Error('unknown kind ' + kind);
}

const TARGETS = [
  ['journal/index.html', 'journal'],
  ['journal/archive/index.html', 'archive'],
  ['journal/dispatches/index.html', 'dispatches'],
  ['changelog/index.html', 'changelog'],
];

function block(ld) {
  return `${START}\n<script type="application/ld+json">\n${JSON.stringify(ld, null, 2)}\n</script>\n${END}`;
}

// Remove any prior marked block, then insert a fresh one before </head>.
function inject(html, ld) {
  const stripped = html.replace(new RegExp(`\\s*${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`, 'g'), '');
  return stripped.replace(/<\/head>/i, `${block(ld)}\n</head>`);
}

function run({ check } = {}) {
  const entries = discoverEntries();
  let changed = 0, problems = 0;
  for (const [rel, kind] of TARGETS) {
    const f = join(ROOT, rel);
    if (!existsSync(f)) { console.error(`✗ missing target ${rel}`); problems++; continue; }
    const html = readFileSync(f, 'utf8');
    const ld = buildLd(kind, entries);
    if (check) {
      const has = html.includes(START) && html.includes('"CollectionPage"');
      const wantItems = kind === 'journal' || kind === 'archive';
      const okItems = !wantItems || html.includes(`"position": ${entries.length}`);
      if (!has) { console.error(`✗ ${rel}: collection JSON-LD missing`); problems++; }
      else if (!okItems) { console.error(`✗ ${rel}: ItemList post count stale (want ${entries.length})`); problems++; }
      continue;
    }
    const next = inject(html, ld);
    if (next !== html) { writeFileSync(f, next, 'utf8'); changed++; }
  }
  if (check) {
    if (problems) { console.error(`✗ inject-collection-jsonld --check: ${problems} listing page(s) missing/stale collection schema`); process.exit(1); }
    console.log(`✓ inject-collection-jsonld --check: ${TARGETS.length} listing page(s) carry collection schema (${entries.length} posts)`);
    process.exit(0);
  }
  console.log(`✓ inject-collection-jsonld: ${changed}/${TARGETS.length} page(s) updated · ${entries.length} journal posts enumerated`);
}

function selfTest() {
  let fail = 0;
  const assert = (c, m) => { if (!c) { console.error('  ✗ ' + m); fail++; } };
  const sample = [
    { slug: 'b', url: PROD + '/journal/b/', headline: 'B Post', datePublished: '2026-02-01T00:00:00Z' },
    { slug: 'a', url: PROD + '/journal/a/', headline: 'A Post', datePublished: '2026-05-01T00:00:00Z' },
  ];
  const ld = buildLd('journal', sample);
  assert(ld['@type'] === 'CollectionPage', 'journal kind is CollectionPage');
  assert(ld.mainEntity['@type'] === 'ItemList', 'mainEntity is ItemList');
  assert(ld.mainEntity.itemListElement.length === 2, 'lists all items');
  assert(ld.mainEntity.itemListElement[0].position === 1, 'positions start at 1');
  const real = discoverEntries();
  assert(real.length >= 5, `discovers real journal entries (got ${real.length})`);
  assert(real.every((e) => e.headline && e.url.startsWith(PROD)), 'every entry has headline + prod url');
  // newest-first ordering
  const dl = buildLd('archive', real);
  assert(dl.mainEntity.itemListElement.length === real.length, 'archive lists every post');
  const injected = inject('<html><head><title>x</title></head><body></body></html>', ld);
  assert(injected.includes(START) && injected.includes('CollectionPage'), 'inject adds marked block');
  const reinjected = inject(injected, ld);
  assert((reinjected.match(/collection-jsonld:start/g) || []).length === 1, 'idempotent — single block after re-run');
  if (fail === 0) { console.log('✓ inject-collection-jsonld --self-test: 9/9 passed'); process.exit(0); }
  console.error(`✗ inject-collection-jsonld --self-test: ${fail} failed`); process.exit(1);
}

const RUN_DIRECT = process.argv[1] && process.argv[1].replace(/\\/g, '/').endsWith('inject-collection-jsonld.mjs');
if (RUN_DIRECT) {
  if (process.argv.includes('--self-test')) selfTest();
  else run({ check: process.argv.includes('--check') });
}
