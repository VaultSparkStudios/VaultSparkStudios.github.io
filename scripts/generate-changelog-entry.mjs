#!/usr/bin/env node
// generate-changelog-entry.mjs — S190: auto-derive a changelog entry HTML block
// from TASK_BOARD.md Done entries + context/PROJECT_STATUS.json.
//
// Produces a ready-to-paste <article class="cl-phase"> block that matches the
// structure in changelog/index.html. NEVER writes directly to changelog/ —
// the draft goes to changelog/_drafts/ for founder review (hand-curated truth).
//
//   node scripts/generate-changelog-entry.mjs          # write draft
//   node scripts/generate-changelog-entry.mjs --self-test
//   node scripts/generate-changelog-entry.mjs --days 60  # wider window
//
// Per DECISIONS (S178): exports are pure; side effects gate on RUN_DIRECT.
// Import-safe: no top-level side effects.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// Internal terms that must not appear in public changelog copy.
const REDACTIONS = [
  [/\bRUM\b/g, 'real-user metrics'],
  [/\bSIL\b/g, 'studio improvement loop'],
  [/\bLCP\b/g, 'page-load time'],
  [/\bTTI\b/g, 'time-to-interactive'],
  [/\bFCP\b/g, 'first paint'],
  [/\bCWV\b/g, 'Core Web Vitals'],
  [/\bCSP\b/g, 'security policy'],
  [/\bTT\b(?!\s*\w)/g, 'browser security'],
  [/build:check\b/g, 'build pipeline'],
  [/check-rum-allowlist\b/gi, 'beacon validation'],
  [/\bwrangler\b/gi, 'edge deploy'],
  [/\bsupabase\b(?!\s+edge)/gi, 'database'],
  [/\bS(\d{3})\b/g, ''],                // strip sprint codes like S186
  [/\bNDJSON\b/gi, 'event log'],
  [/\bKV\b(?!\s*\w)/g, 'edge cache'],
  [/\bR2\b(?!\s*\w)/g, 'object storage'],
  [/\bCF Pages\b/gi, 'the CDN'],
  [/\bCF\b(?:\s+)/g, 'Cloudflare '],
  [/\[skip ci\]/gi, ''],
  [/--check\b/g, ''],
  [/--self-test\b/g, ''],
  [/\bPR\s+#\d+\b/g, ''],
];

// Categories of done-line that are NOT public-safe (suppress from changelog).
const INTERNAL_PATTERNS = [
  /context\/|TASK_BOARD|HANDOFF|LATEST_HANDOFF|SESSION_PROTOCOL/i,
  /PROJECT_STATUS\.json|CURRENT_STATE\.md|SELF_IMPROVEMENT/i,
  /deploy trigger|skip ci|reconcile|closeout/i,
  /\[skip ci\]|\[INTERNAL\]|\[ADMIN\]/i,
  /scripts\/check-|scripts\/build-|scripts\/validate-/i,
];

/** Sanitize a line for public changelog copy. */
export function sanitize(line) {
  let s = line;
  for (const [pattern, replacement] of REDACTIONS) {
    s = s.replace(pattern, replacement);
  }
  // Collapse extra whitespace from removals
  return s.replace(/\s{2,}/g, ' ').trim();
}

/** Check whether a done line is safe for public display. */
export function isPublicSafe(line) {
  return !INTERNAL_PATTERNS.some((p) => p.test(line));
}

/** Extract [x] done lines from TASK_BOARD, filter internal items, sanitize. */
export function extractChangelogItems(taskBoard, maxItems = 12) {
  return taskBoard.split('\n')
    .filter((l) => /^\s*-\s*\[x\]/.test(l))
    .map((l) => l.replace(/^\s*-\s*\[x\]\s*/, '').replace(/\*\*/g, '').trim())
    .filter((l) => l.length > 5)
    .filter(isPublicSafe)
    .map(sanitize)
    .filter((l) => l.length > 5)
    .slice(0, maxItems);
}

/** Derive a short release title from the currentFocus field. */
export function deriveTitle(currentFocus) {
  if (!currentFocus) return 'Infrastructure, performance, and UX polish';
  const clean = sanitize(currentFocus);
  // Capitalise first letter if not already
  return clean.charAt(0).toUpperCase() + clean.slice(1);
}

/** Escape HTML entities for safe insertion into HTML attributes / content. */
export function escapeHtml(str) {
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Build an HTML changelog entry.
 *
 * @param {{ items: string[], session: string|null, date: string, title: string, isLive?: boolean }} opts
 * @returns {string} HTML block ready to paste into changelog/index.html
 */
export function buildEntry({ items = [], session = null, date = '', title = '', isLive = false } = {}) {
  const sessionLabel = session ? String(session) : '—';
  const phaseClass = ['cl-phase', isLive ? 'cl-phase--live' : '', 'js-cl-phase']
    .filter(Boolean).join(' ');
  const itemsHtml = items.length
    ? items.map((item) => `              <li>${escapeHtml(item)}</li>`).join('\n')
    : `              <li>_(No public-safe done items found in this window — fill in manually.)_</li>`;

  return [
    `          <!-- ${escapeHtml(sessionLabel)} — generated by scripts/generate-changelog-entry.mjs — DRAFT -->`,
    `          <article class="${phaseClass}" data-reveal="fade-up">`,
    `            <div class="cl-dot" aria-hidden="true"></div>`,
    `            <div class="cl-phase-header">`,
    `              <span class="cl-phase-num">${escapeHtml(sessionLabel)}</span>` +
      (date ? `<span class="cl-phase-date">${escapeHtml(date)}</span>` : ''),
    `              <div class="cl-phase-title">${escapeHtml(title)}</div>`,
    `            </div>`,
    `            <ul class="cl-items">`,
    itemsHtml,
    `            </ul>`,
    `          </article>`,
  ].join('\n');
}

function selfTest() {
  let pass = 0, fail = 0;
  const check = (n, c) => { c ? pass++ : (fail++, console.log('  ✗ ' + n)); };

  // sanitize
  check('sanitize strips S186', !sanitize('[UX] S186 fix').includes('S186'));
  check('sanitize replaces RUM', sanitize('RUM rollup gate').includes('real-user metrics'));
  check('sanitize keeps brand', sanitize('Vault Sparked feature').includes('Vault'));
  check('sanitize strips [skip ci]', !sanitize('[skip ci] trigger').includes('skip ci'));

  // isPublicSafe
  check('isPublicSafe: skip ci → false', !isPublicSafe('chore(deploy): trigger CF Pages [skip ci]'));
  check('isPublicSafe: UX feature → true', isPublicSafe('[UX] improved nav sheet animation'));
  check('isPublicSafe: context/ path → false', !isPublicSafe('update context/TASK_BOARD.md'));

  // extractChangelogItems
  const board = [
    '- [x] **[UX]** S186 Oracle empty-state chips shipped',
    '- [ ] open item not done',
    '- [x] chore(deploy): trigger CF Pages build [skip ci]',
    '- [x] **[Feat]** Progressive membership unlock (3-stage)',
    '- [x] update context/LATEST_HANDOFF.md',
  ].join('\n');
  const items = extractChangelogItems(board);
  check('extractChangelogItems: excludes deploy trigger', !items.some((i) => /deploy trigger/i.test(i)));
  check('extractChangelogItems: excludes context/', !items.some((i) => /LATEST_HANDOFF/i.test(i)));
  check('extractChangelogItems: includes UX feature', items.some((i) => /Oracle|empty.state/i.test(i)));
  check('extractChangelogItems: excludes open item', items.length < 4); // max 3 public-safe items in test

  // buildEntry
  const html = buildEntry({ items: ['Improved nav speed'], session: 'S190', date: '2026-06-11', title: 'Test title' });
  check('buildEntry: has cl-phase', html.includes('cl-phase'));
  check('buildEntry: has session label', html.includes('S190'));
  check('buildEntry: has item', html.includes('Improved nav speed'));
  check('buildEntry: is DRAFT comment', html.includes('DRAFT'));

  // deriveTitle
  check('deriveTitle: capitalises', deriveTitle('funnel measurement loop closed').startsWith('F'));
  check('deriveTitle: fallback', deriveTitle(null).includes('Infrastructure'));

  console.log(`generate-changelog-entry self-test: ${pass}/${pass + fail} passing`);
  return fail === 0;
}

const RUN_DIRECT = (import.meta.main ?? (process.argv[1] && process.argv[1].endsWith('generate-changelog-entry.mjs')));

if (RUN_DIRECT) {
  const argv = process.argv.slice(2);
  if (argv.includes('--self-test')) process.exit(selfTest() ? 0 : 1);

  // Read inputs
  let board = '';
  let status = {};
  try { board = readFileSync(join(ROOT, 'context', 'TASK_BOARD.md'), 'utf8'); } catch { console.error('! cannot read TASK_BOARD.md'); }
  try { status = JSON.parse(readFileSync(join(ROOT, 'context', 'PROJECT_STATUS.json'), 'utf8')); } catch {}

  const session = status.currentSession ? `S${status.currentSession}` : null;
  const date = (status.lastUpdated || '').slice(0, 10) || new Date().toISOString().slice(0, 10);
  const title = deriveTitle(status.currentFocus || '');
  const items = extractChangelogItems(board);

  const html = buildEntry({ items, session, date, title });
  const draftsDir = join(ROOT, 'changelog', '_drafts');
  if (!existsSync(draftsDir)) mkdirSync(draftsDir, { recursive: true });
  const out = join(draftsDir, `entry-${date}.html`);
  writeFileSync(out, html + '\n');

  console.log(`✓ changelog entry draft → ${out}`);
  console.log(`  Session: ${session || '(unknown)'}  ·  Items: ${items.length} public-safe`);
  console.log('  (DRAFT only — paste into changelog/index.html after founder review.)');
}
