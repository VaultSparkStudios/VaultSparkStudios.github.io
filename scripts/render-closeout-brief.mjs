#!/usr/bin/env node
/**
 * render-closeout-brief.mjs
 *
 * Canonical closeout impact brief renderer. Reads the closeout JSON contract,
 * prints a founder-facing brief, and archives it under docs/.
 */

import fs from 'node:fs';
import path from 'node:path';
import { render } from './lib/skill-brief.mjs';

function argVal(name) {
  const idx = process.argv.indexOf(name);
  return idx >= 0 ? process.argv[idx + 1] : null;
}

if (process.argv.includes('--schema')) {
  console.log(JSON.stringify({
    session: 'S245',
    date: '2026-07-01',
    agent: 'codex',
    repo: 'VaultSparkStudios.github.io',
    headline: 'One-sentence closeout headline.',
    items: [{
      id: '#1',
      slug: 'brief-renderer-restore',
      title: 'Closeout brief renderer restored',
      axis: 'organization',
      projectImpact: 8,
      ecosystemImpact: 6,
      insight: 'Closeout now renders from a local script again. The next session gets the canonical visual proof instead of a missing-file gap.',
      evidence: 'scripts/render-closeout-brief.mjs',
    }],
    followUps: [],
    blockers: [],
  }, null, 2));
  process.exit(0);
}

const input = argVal('--input');
if (!input) {
  console.error('usage: node scripts/render-closeout-brief.mjs --input <brief.json> [--stdout-only]');
  console.error('       node scripts/render-closeout-brief.mjs --schema');
  process.exit(2);
}

const brief = JSON.parse(fs.readFileSync(input, 'utf8'));
brief.kind ||= 'closeout';
for (const item of brief.items || []) {
  if (item.leftScore == null && item.projectImpact != null) item.leftScore = item.projectImpact;
  if (item.rightScore == null && item.ecosystemImpact != null) item.rightScore = item.ecosystemImpact;
}

const text = render(brief, { actionGate: `${(brief.items || []).length} items shipped · ready to commit & push? [y/N]` });
process.stdout.write(text + '\n');

if (!process.argv.includes('--stdout-only')) {
  const docsDir = path.join(process.cwd(), 'docs');
  fs.mkdirSync(docsDir, { recursive: true });
  const outPath = path.join(docsDir, `CLOSEOUT_BRIEF_${brief.session}_${brief.date}.md`);
  fs.writeFileSync(outPath, '```\n' + text + '\n```\n\n---\n\n*Generated by `scripts/render-closeout-brief.mjs` · spec: `docs/CLOSEOUT_BRIEF_SPEC.md`*\n');
  console.error(`\n✓ archived: ${outPath}`);
}
