#!/usr/bin/env node
/**
 * build-proposed-edges.mjs — S218 (second-order innovation)
 *
 * Turns the deliberately-EMPTY projectGraph into a founder curation surface — without
 * violating D-S218.5 (projectGraph edges must be founder-confirmed; never auto-inferred,
 * because shared-type/phase edges would be noise). The constellation in studio-living.js
 * consumes projectGraph.{nodes,edges}, but PROJECT_EDGES in generate-public-intelligence.mjs
 * is empty ("All edges must be founder-confirmed"), so the constellation renders nothing.
 *
 * This bridges the gap: it reuses the B2 ecosystem-bridge category-token AFFINITY model to
 * PROPOSE candidate edges (from the public catalog) into context/PROPOSED_GRAPH_EDGES.md —
 * a founder-facing doc, NOT a served api/ surface and NOT projectGraph itself. Proposals are
 * pre-typed for the renderer's edge classes (shares-universe / builds-on / sibling). The
 * founder confirms the good ones into PROJECT_EDGES; nothing is asserted as a real edge until
 * they do. So the policy holds (no inferred public claims) AND the dead feature gets a path
 * to life. Pure fs (no spawns) — safe under the Windows Git Bash throttle.
 *
 *   node scripts/build-proposed-edges.mjs            # regenerate the proposal doc
 *   node scripts/build-proposed-edges.mjs --check    # fail if the doc is out of sync (CI)
 *   node scripts/build-proposed-edges.mjs --self-test
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'context', 'PROPOSED_GRAPH_EDGES.md');

// Generic category tokens that appear across unrelated products — including them would
// re-create the "shared type is noise" problem D-S218.5 warns about. Excluded from affinity.
const STOP = new Set(['ai', 'tool', 'platform', 'os', 'product', 'world', 'sim']);

function tokens(category) {
  return (category || '').toLowerCase().split(/[^a-z0-9]+/).filter((t) => t && !STOP.has(t));
}

// Map a shared theme token to the renderer's edge-type class (studio-living.js:
// graph-edge--shares-universe / --builds-on / --sibling).
function edgeType(shared) {
  const s = new Set(shared);
  if (s.has('survival') || s.has('narrative') || s.has('cinematic') || s.has('crafting')) return 'shares-universe';
  if (s.has('agent') || s.has('trust') || s.has('intelligence')) return 'builds-on';
  return 'sibling';
}

function loadCatalog(pi) {
  const raw = pi.catalog ? Object.values(pi.catalog) : [];
  return raw.map((c) => {
    let url = null;
    if (existsSync(join(ROOT, 'games', c.id, 'index.html'))) url = `/games/${c.id}/`;
    else if (existsSync(join(ROOT, 'projects', c.id, 'index.html'))) url = `/projects/${c.id}/`;
    return { id: c.id, name: c.name, type: c.type, category: c.category || '', url };
  });
}

// Unordered affinity pairs (both items must have a real page), ranked by shared-token count
// then name for determinism. Only pairs sharing ≥1 NON-generic theme token are proposed.
function proposeEdges(catalog) {
  const items = catalog.filter((c) => c.url);
  const edges = [];
  for (let i = 0; i < items.length; i++) {
    for (let j = i + 1; j < items.length; j++) {
      const a = items[i], b = items[j];
      const at = tokens(a.category), bt = tokens(b.category);
      const shared = at.filter((t) => bt.includes(t));
      if (!shared.length) continue;
      edges.push({ from: a.id, to: b.id, fromName: a.name, toName: b.name, shared, score: shared.length, type: edgeType(shared) });
    }
  }
  edges.sort((x, y) => y.score - x.score || x.from.localeCompare(y.from) || x.to.localeCompare(y.to));
  return edges;
}

function render(edges, generatedAt) {
  const lines = [];
  lines.push('# Proposed projectGraph Edges — UNCONFIRMED (founder curation surface)');
  lines.push('');
  lines.push('> Generated by `scripts/build-proposed-edges.mjs` (S218). Do NOT treat these as live edges.');
  lines.push('> `projectGraph.edges` in `api/public-intelligence.json` stays EMPTY until the founder');
  lines.push('> confirms an edge here into `PROJECT_EDGES` in `scripts/generate-public-intelligence.mjs`');
  lines.push('> (**D-S218.5** — relationship edges must be founder-confirmed, never auto-inferred).');
  lines.push('> These are affinity-derived *candidates* (shared non-generic category theme) to review,');
  lines.push('> not assertions. The constellation in `assets/studio-living.js` will render whatever the');
  lines.push('> founder promotes.');
  lines.push('');
  if (!edges.length) {
    lines.push('_No affinity candidates (no two catalog items share a non-generic theme token)._');
  } else {
    lines.push('| Confirm? | From | To | Shared theme | Suggested type |');
    lines.push('|---|---|---|---|---|');
    for (const e of edges) {
      lines.push(`| \`[ ]\` | ${e.fromName} (\`${e.from}\`) | ${e.toName} (\`${e.to}\`) | ${e.shared.join(', ')} | \`${e.type}\` |`);
    }
    lines.push('');
    lines.push('To confirm an edge, add `{ from: "<from>", to: "<to>", type: "<type>", label: "<short label>" }`');
    lines.push('to `PROJECT_EDGES` in `scripts/generate-public-intelligence.mjs`, then rebuild.');
  }
  lines.push('');
  lines.push(`<!-- generated-at: ${generatedAt} · ${edges.length} candidate(s) -->`);
  lines.push('');
  return lines.join('\n');
}

// Body without the timestamp line — what --check compares (timestamp is volatile).
function stableBody(md) {
  return md.replace(/<!-- generated-at:[^>]*-->/g, '').trim();
}

function selfTest() {
  const pi = { catalog: { 0: { id: 'solara', name: 'Solara', type: 'game', category: 'Survival World' },
                          1: { id: 'the-exodus', name: 'The Exodus', type: 'game', category: 'Narrative Survival' },
                          2: { id: 'promogrind', name: 'PromoGrind', type: 'tool', category: 'Creator Tool' } } };
  // Fake url resolver: pretend all three have pages.
  const catalog = Object.values(pi.catalog).map((c) => ({ ...c, category: c.category, url: `/x/${c.id}/` }));
  const edges = proposeEdges(catalog);
  const assert = (c, m) => { if (!c) { console.error('  ✗ ' + m); process.exitCode = 1; } else console.log('  ✓ ' + m); };
  const se = edges.find((e) => (e.from === 'solara' && e.to === 'the-exodus') || (e.from === 'the-exodus' && e.to === 'solara'));
  assert(!!se, 'proposes solara↔the-exodus (shared "survival")');
  assert(se && se.type === 'shares-universe', 'types the survival pair as shares-universe');
  assert(!edges.some((e) => e.from === 'promogrind' || e.to === 'promogrind'), 'does NOT link PromoGrind (no shared non-generic theme; "tool" is generic)');
  if (process.exitCode) console.error('build-proposed-edges self-test FAILED'); else console.log('build-proposed-edges self-test passed');
}

const CHECK = process.argv.includes('--check');
if (process.argv.includes('--self-test')) {
  selfTest();
} else {
  const piPath = join(ROOT, 'api', 'public-intelligence.json');
  if (!existsSync(piPath)) { console.log('build-proposed-edges: no public-intelligence.json — skip'); process.exit(0); }
  const pi = JSON.parse(readFileSync(piPath, 'utf8'));
  const edges = proposeEdges(loadCatalog(pi));
  // Deterministic timestamp for --check (avoid Date.now churn): reuse the feed's generatedAt.
  const stamp = pi.generatedAt || 'unknown';
  const md = render(edges, stamp);
  if (CHECK) {
    if (!existsSync(OUT)) { console.error('✗ build-proposed-edges --check: context/PROPOSED_GRAPH_EDGES.md missing — run the generator'); process.exit(1); }
    if (stableBody(readFileSync(OUT, 'utf8')) !== stableBody(md)) {
      console.error('✗ build-proposed-edges --check: PROPOSED_GRAPH_EDGES.md out of sync with the catalog — run: node scripts/build-proposed-edges.mjs');
      process.exit(1);
    }
    console.log(`✓ build-proposed-edges --check: ${edges.length} candidate(s) in sync`);
  } else {
    writeFileSync(OUT, md);
    console.log(`✓ build-proposed-edges: ${edges.length} affinity candidate(s) → context/PROPOSED_GRAPH_EDGES.md (founder-confirm to activate)`);
  }
}
