#!/usr/bin/env node
/**
 * check-hero-lcp-element.mjs (S226 second-order innovation)
 *
 * Verifies the featured hero tile cover uses <picture><img fetchpriority="high">
 * (not a CSS background <span>). CSS image-set() backgrounds are not matched by
 * Chrome's <link rel="preload">, so the image is late-discovered (~3s Load Delay).
 * A real <img> with fetchpriority="high" is discovered directly from HTML, cutting
 * LCP Load Delay to near 0 and unlocking the browser's native LCP fast-path.
 *
 * This gate prevents the S226 LCP fix from silently regressing when the hero
 * showcase is regenerated by build-hero-portfolio.mjs.
 *
 * Checks:
 *   1. hero-showcase:start block contains hero-tile__cover--lcp class
 *   2. Featured tile cover has <picture>...<img fetchpriority="high">
 *   3. <head> contains <link rel="preload" as="image"> for the AVIF cover
 *   4. The first-viewport wordmark letters have no CSS animation that can defer
 *      text Largest Contentful Paint behind main-thread work
 *
 * Exit: 0 = OK · 1 = regression detected
 *
 * Usage:
 *   node scripts/check-hero-lcp-element.mjs
 *   node scripts/check-hero-lcp-element.mjs --self-test
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const INDEX = path.join(ROOT, 'index.html');

const args = process.argv.slice(2);
const SELF_TEST = args.includes('--self-test');

// ── Pure checks ──────────────────────────────────────────────────────────────

export function checkHeroLcpElement(html) {
  const errors = [];

  // Extract the hero-showcase block
  const showcase = (html.match(/<!-- hero-showcase:start -->([\s\S]*?)<!-- hero-showcase:end -->/) || [])[1] || '';
  if (!showcase) { errors.push('hero-showcase markers not found in index.html'); return errors; }

  // Extract the featured tile (first hero-tile--featured element)
  const featuredMatch = showcase.match(/<(?:div|a)[^>]*hero-tile--featured[^>]*>([\s\S]*?)<\/(?:div|a)>/);
  const featured = featuredMatch ? featuredMatch[0] : '';
  if (!featured) { errors.push('hero-tile--featured not found in hero-showcase'); return errors; }

  // Check 1: featured tile must use hero-tile__cover--lcp class
  if (!featured.includes('hero-tile__cover--lcp')) {
    errors.push('hero-tile--featured cover does not have hero-tile__cover--lcp class (CSS background will block LCP preload matching)');
  }

  // Check 2: featured cover must contain <picture> with <img fetchpriority="high">
  if (!featured.includes('<picture>') || !featured.includes('fetchpriority="high"')) {
    errors.push('hero-tile--featured cover must use <picture><img fetchpriority="high"> — CSS background image-set() cannot be matched by Chrome preload hints');
  }

  // Check 3: featured cover must have an AVIF source
  if (!featured.includes('type="image/avif"')) {
    errors.push('hero-tile--featured <picture> must have <source type="image/avif"> for AVIF preload to match');
  }

  // Check 4: <head> must have <link rel="preload" as="image"> for the LCP image
  const headMatch = html.match(/<head[\s\S]*?<\/head>/i);
  const head = headMatch ? headMatch[0] : html.substring(0, 2000);
  if (!head.includes('rel="preload"') || !head.includes('as="image"')) {
    errors.push('<head> missing <link rel="preload" as="image"> for LCP cover image');
  }

  // Check 5: non-featured tiles must NOT use hero-tile__cover--lcp (keep CSS background)
  const nonFeaturedHtml = showcase.replace(featured, '');
  if (nonFeaturedHtml.includes('hero-tile__cover--lcp')) {
    errors.push('hero-tile__cover--lcp found on non-featured tile — only the featured (LCP) tile should use picture/img');
  }

  // Check 6: Lighthouse may select the visible wordmark text as the page LCP.
  // Animating that node makes Chrome defer LCP until the animation completes;
  // under main-thread contention a sub-second animation became a 5.4s LCP.
  const forgeLetterBlocks = [...html.matchAll(/[^{}]*\.forge-letter[^{}]*\{([^}]*)\}/g)];
  const unsafeWordmarkAnimation = forgeLetterBlocks.some((match) =>
    [...match[1].matchAll(/\banimation(?:-name)?\s*:\s*([^;}]+)/gi)]
      .some((declaration) => !/^none(?:\s|$)/i.test(declaration[1].trim())),
  );
  if (unsafeWordmarkAnimation) {
    errors.push('.forge-letter must not animate — the visible wordmark is a live text LCP candidate');
  }

  return errors;
}

// ── Self-test ────────────────────────────────────────────────────────────────

if (SELF_TEST) {
  let passed = 0;
  const assert = (ok, m) => { if (!ok) { console.error('  ✗ ' + m); process.exit(1); } console.log('  ✓ ' + m); passed++; };

  // PASS case: correct picture/img structure
  const goodHtml = `<head>
  <!-- hero-lcp-preload:start --><link rel="preload" as="image" href="/assets/covers/doodie.avif" type="image/avif" fetchpriority="high"><!-- hero-lcp-preload:end -->
</head>
<body>
<!-- hero-showcase:start --><div class="hero-tile hero-tile--featured has-cover"><span class="hero-tile__cover hero-tile__cover--lcp" aria-hidden="true"><picture><source srcset="/assets/covers/doodie.avif" type="image/avif"><source srcset="/assets/covers/doodie.webp" type="image/webp"><img src="/assets/covers/doodie.png" fetchpriority="high" decoding="async" alt=""></picture></span></div><div class="hero-tile ht-other no-cover"><span class="hero-tile__cover" aria-hidden="true"></span></div><!-- hero-showcase:end -->
</body>`;
  const goodErrors = checkHeroLcpElement(goodHtml);
  assert(goodErrors.length === 0, `PASS: valid structure → 0 errors (got: ${goodErrors.join(', ')})`);

  // FAIL case: CSS background span on featured tile
  const badHtml = `<head><link rel="preload" as="image" href="/assets/covers/doodie.avif" type="image/avif"></head>
<body><!-- hero-showcase:start --><div class="hero-tile hero-tile--featured has-cover"><span class="hero-tile__cover" aria-hidden="true"></span></div><!-- hero-showcase:end --></body>`;
  const badErrors = checkHeroLcpElement(badHtml);
  assert(badErrors.length > 0, 'FAIL: CSS background span → errors detected');
  assert(badErrors.some(e => e.includes('hero-tile__cover--lcp')), 'FAIL: error mentions missing --lcp class');

  // FAIL case: no preload in head
  const noPreloadHtml = `<head></head>
<body><!-- hero-showcase:start --><div class="hero-tile hero-tile--featured has-cover"><span class="hero-tile__cover hero-tile__cover--lcp"><picture><source srcset="/assets/covers/doodie.avif" type="image/avif"><img src="/assets/covers/doodie.png" fetchpriority="high" alt=""></picture></span></div><!-- hero-showcase:end --></body>`;
  const noPreloadErrors = checkHeroLcpElement(noPreloadHtml);
  assert(noPreloadErrors.some(e => e.includes('preload')), 'FAIL: missing preload → error detected');

  const animatedWordmark = goodHtml.replace('</head>', '<style>.forge-letter { animation: letterForge .3s; }</style></head>');
  const animatedErrors = checkHeroLcpElement(animatedWordmark);
  assert(animatedErrors.some(e => e.includes('.forge-letter must not animate')), 'FAIL: animated wordmark LCP → error detected');

  console.log(`\ncheck-hero-lcp-element self-test: ${passed} passing`);
  process.exit(0);
}

// ── Main ─────────────────────────────────────────────────────────────────────

let html;
try {
  html = fs.readFileSync(INDEX, 'utf8');
} catch (e) {
  console.error(`check-hero-lcp-element: cannot read index.html — ${e.message}`);
  process.exit(1);
}

const errors = checkHeroLcpElement(html);
if (errors.length === 0) {
  console.log('check-hero-lcp-element: ✓ image preload is matchable and wordmark text LCP is animation-free');
  process.exit(0);
} else {
  for (const e of errors) console.error('check-hero-lcp-element: ✗ ' + e);
  console.error('check-hero-lcp-element: LCP regression detected — run node scripts/build-hero-portfolio.mjs to regenerate');
  process.exit(1);
}
