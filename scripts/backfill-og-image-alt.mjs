#!/usr/bin/env node
/**
 * backfill-og-image-alt.mjs — Add og:image:alt and twitter:image:alt to every
 * public HTML page that has og:image / twitter:image but is missing the alt tags.
 *
 * Accessibility + social-card quality: assistive technologies read og:image:alt
 * when rendering link unfurls, and both Slack and LinkedIn surface it in their
 * accessibility trees. The homepage had these tags; secondary pages did not.
 *
 * Alt text is derived from og:title (for og:image:alt) and twitter:title or
 * og:title (for twitter:image:alt). Falls back to the page <title> if needed.
 *
 * Skips the same private/internal paths as backfill-meta-descriptions.mjs plus
 * news articles (those are generated by generate-news-pages.mjs and carry their
 * own templated meta).
 *
 * Usage: node scripts/backfill-og-image-alt.mjs [--dry-run]
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..');
const DRY = process.argv.includes('--dry-run');

const SKIP_PATH_PATTERNS = [
  /^investor(\/|-portal\/)/i,
  /^studio-hub\//i,
  /^vault-member\/admin\//i,
  /^vault-treasury\//i,
  /^news\//i,                    // generated by generate-news-pages.mjs — has own templating
  /^open-source\//i,
  /^franchise-architect\/game\.html$/i,
  /^vaultfront\/404\.html$/i,
  /^franchise-architect\/404\.html$/i,
  /google-site-verification/i,
  /\/offline\.html$/i,
  /\/\.ai\/index\.html$/,        // agent-facing surfaces
];

function walk(dir, base = dir, acc = []) {
  for (const entry of fs.readdirSync(dir)) {
    if (['node_modules', 'playwright-report', 'test-results', '.git'].includes(entry)) continue;
    const full = path.join(dir, entry);
    const rel = path.relative(base, full).replace(/\\/g, '/');
    if (fs.statSync(full).isDirectory()) walk(full, base, acc);
    else if (entry.endsWith('.html')) acc.push({ full, rel });
  }
  return acc;
}

function extractMeta(html, property) {
  const patterns = [
    new RegExp(`<meta\\s[^>]*(?:property|name)=["']${property}["'][^>]*content="([^"]*)"`, 'i'),
    new RegExp(`<meta\\s[^>]*(?:property|name)=["']${property}["'][^>]*content='([^']*)'`, 'i'),
    new RegExp(`<meta\\s[^>]*content="([^"]*)"[^>]*(?:property|name)=["']${property}["']`, 'i'),
    new RegExp(`<meta\\s[^>]*content='([^']*)'[^>]*(?:property|name)=["']${property}["']`, 'i'),
  ];
  for (const re of patterns) {
    const m = re.exec(html);
    if (m) return m[1].trim();
  }
  return null;
}

function extractTitle(html) {
  const m = /<title>([^<]+)<\/title>/i.exec(html);
  return m ? m[1].trim() : null;
}

function hasProperty(html, property) {
  return new RegExp(`<meta\\s[^>]*(?:property|name)=["']${property}["']`, 'i').test(html);
}

function insertAfter(html, afterProperty, newTag) {
  const re = new RegExp(`(<meta\\s[^>]*(?:property|name)=["']${afterProperty}["'][^>]*>)`, 'i');
  return html.replace(re, `$1\n  ${newTag}`);
}

function buildAltTag(property, value) {
  return `<meta property="${property}" content="${value.replace(/"/g, '&quot;')}" />`;
}

let changed = 0;
let skipped = 0;

const files = walk(ROOT).filter(({ rel }) => {
  if (SKIP_PATH_PATTERNS.some((p) => p.test(rel))) return false;
  return true;
});

for (const { full, rel } of files) {
  let html = fs.readFileSync(full, 'utf8');
  let modified = false;

  const hasOgImage = hasProperty(html, 'og:image');
  const hasOgAlt = hasProperty(html, 'og:image:alt');
  const hasTwitterImage = hasProperty(html, 'twitter:image');
  const hasTwitterAlt = hasProperty(html, 'twitter:image:alt');

  if (!hasOgImage && !hasTwitterImage) { skipped++; continue; }

  if (hasOgImage && !hasOgAlt) {
    const altText =
      extractMeta(html, 'og:title') ||
      extractTitle(html) ||
      'VaultSpark Studios';

    let insertPoint = 'og:image:type';
    if (!hasProperty(html, 'og:image:type')) {
      insertPoint = 'og:image:height';
      if (!hasProperty(html, 'og:image:height')) {
        insertPoint = 'og:image:width';
        if (!hasProperty(html, 'og:image:width')) {
          insertPoint = 'og:image';
        }
      }
    }

    html = insertAfter(html, insertPoint, buildAltTag('og:image:alt', altText));
    modified = true;
  }

  if (hasTwitterImage && !hasTwitterAlt) {
    const altText =
      extractMeta(html, 'twitter:title') ||
      extractMeta(html, 'og:title') ||
      extractTitle(html) ||
      'VaultSpark Studios';

    html = insertAfter(html, 'twitter:image', buildAltTag('twitter:image:alt', altText));
    modified = true;
  }

  if (modified) {
    if (!DRY) {
      fs.writeFileSync(full, html, 'utf8');
    }
    console.log(`${DRY ? '[dry]' : '[fix]'} ${rel}`);
    changed++;
  } else {
    skipped++;
  }
}

console.log(`\n${DRY ? 'Would patch' : 'Patched'} ${changed} files, skipped ${skipped}.`);
